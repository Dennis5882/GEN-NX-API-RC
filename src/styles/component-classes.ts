export function uiClass(value: string | undefined, id?: string): string {
  const classes = value?.split(/\s+/).filter(Boolean) ?? []
  return [
    ...classes,
    ...classes.map(name => utilities[name]).filter(Boolean),
    ...(id && utilities['#' + id] ? [utilities['#' + id]] : []),
  ].join(' ')
}
